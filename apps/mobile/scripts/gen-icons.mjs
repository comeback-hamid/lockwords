// Writes src/components/icon-paths.ts with only the Octicons the app uses. Run: npm run icons:gen
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const octicons = createRequire(import.meta.url)('@primer/octicons');

// our name → Octicon name. Octicons has no plane or food icon, so the nearest glyph is used.
const ICONS = {
  back: 'chevron-left', pencil: 'pencil', check: 'check', send: 'arrow-up', mic: 'unmute', generate: 'zap', close: 'x', speaker: 'unmute',
  travel: 'paper-airplane', work: 'briefcase', globe: 'globe', people: 'people', bulb: 'light-bulb', school: 'mortar-board',
  food: 'flame', business: 'graph', tech: 'cpu', science: 'telescope', music: 'play', movies: 'video', books: 'book',
  sports: 'trophy', fitness: 'pulse', health: 'heart', nature: 'sun', animals: 'squirrel', art: 'paintbrush', fashion: 'tag',
  gaming: 'device-desktop', news: 'megaphone', family: 'home', friends: 'comment-discussion', shopping: 'package',
  cooking: 'beaker', money: 'credit-card', culture: 'milestone', lock: 'lock', thumbsup: 'thumbsup',
};

const d = (name, size) => {
  const icon = octicons[name];
  if (!icon?.heights[size]) throw new Error(`no Octicon ${name} at ${size}`);
  return [...icon.heights[size].path.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
};
const body = Object.entries(ICONS)
  .map(([ours, theirs]) => `  ${JSON.stringify(ours)}: { 16: ${JSON.stringify(d(theirs, 16))}, 24: ${JSON.stringify(d(theirs, 24))} },`)
  .join('\n');
writeFileSync(
  new URL('../src/components/icon-paths.ts', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from @primer/octicons. Do not edit by hand.\nexport const iconPaths = {\n${body}\n} as const;\n`,
);
console.log(`wrote ${Object.keys(ICONS).length} icons`);
