// Writes src/components/icon-paths.ts with only the Octicons the app uses. Run: npm run icons:gen
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const octicons = createRequire(import.meta.url)('@primer/octicons');

// our name → Octicon name. Octicons has no plane or food icon, so the nearest glyph is used. The mic is our own (OWN below).
const ICONS = {
  back: 'chevron-left', pencil: 'pencil', check: 'check', send: 'arrow-up', generate: 'zap', close: 'x', speaker: 'unmute', plus: 'plus',
  travel: 'paper-airplane', work: 'briefcase', globe: 'globe', people: 'people', bulb: 'light-bulb', school: 'mortar-board',
  food: 'flame', business: 'graph', tech: 'cpu', science: 'telescope', music: 'play', movies: 'video', books: 'book',
  sports: 'trophy', health: 'heart', nature: 'sun', animals: 'squirrel', art: 'paintbrush',
  news: 'megaphone', family: 'home', friends: 'comment-discussion', shopping: 'package',
  money: 'credit-card', culture: 'milestone', lock: 'lock', thumbsup: 'thumbsup', sparkle: 'sparkle', stack: 'stack', home: 'home', left: 'arrow-left', right: 'arrow-right', up: 'arrow-up', deck: 'copy',
};

const d = (name, size) => {
  const icon = octicons[name];
  if (!icon?.heights[size]) throw new Error(`no Octicon ${name} at ${size}`);
  return [...icon.heights[size].path.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
};
// Glyphs Octicons does not have, drawn in the same style (1.5 stroke look, 16 and 24 boxes).
const OWN = {
  mic: {
    16: ['M8 1a2.5 2.5 0 0 0-2.5 2.5v4a2.5 2.5 0 0 0 5 0v-4A2.5 2.5 0 0 0 8 1Zm-1 2.5a1 1 0 0 1 2 0v4a1 1 0 0 1-2 0v-4Z', 'M3.75 6.75a.75.75 0 0 1 .75.75 3.5 3.5 0 1 0 7 0 .75.75 0 0 1 1.5 0 5 5 0 0 1-4.25 4.944V14h1.5a.75.75 0 0 1 0 1.5h-4.5a.75.75 0 0 1 0-1.5h1.5v-1.556A5 5 0 0 1 3 7.5a.75.75 0 0 1 .75-.75Z'],
    24: ['M12 2a3.5 3.5 0 0 0-3.5 3.5v6a3.5 3.5 0 1 0 7 0v-6A3.5 3.5 0 0 0 12 2Zm-2 3.5a2 2 0 1 1 4 0v6a2 2 0 1 1-4 0v-6Z', 'M5.75 10.5a.75.75 0 0 1 .75.75 5.5 5.5 0 1 0 11 0 .75.75 0 0 1 1.5 0 7 7 0 0 1-6.25 6.96V21h2.5a.75.75 0 0 1 0 1.5h-6.5a.75.75 0 0 1 0-1.5h2.5v-2.79A7 7 0 0 1 5 11.25a.75.75 0 0 1 .75-.75Z'],
  },
};
const body = [
  ...Object.entries(ICONS).map(([ours, theirs]) => `  ${JSON.stringify(ours)}: { 16: ${JSON.stringify(d(theirs, 16))}, 24: ${JSON.stringify(d(theirs, 24))} },`),
  ...Object.entries(OWN).map(([ours, paths]) => `  ${JSON.stringify(ours)}: { 16: ${JSON.stringify(paths[16])}, 24: ${JSON.stringify(paths[24])} },`),
].join('\n');
writeFileSync(
  new URL('../src/components/icon-paths.ts', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from @primer/octicons. Do not edit by hand.\nexport const iconPaths = {\n${body}\n} as const;\n`,
);
console.log(`wrote ${Object.keys(ICONS).length + Object.keys(OWN).length} icons`);
